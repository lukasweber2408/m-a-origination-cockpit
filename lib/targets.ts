export function getTargetById(id: string): CompanyTarget | undefined {
  return targets.find((t) => t.id === id);
}

export function getTargetsBySector(sector: SectorType): CompanyTarget[] {
  return targets.filter((t) => t.sector === sector);
}

export function getReviewQueue(): ReviewQueueItem[] {
  const priorityOrder: Record<string, number> = {
    flagged: 0,
    incomplete: 1,
    needs_validation: 2,
    low_confidence: 3,
    reviewed: 4,
  };

  return targets
    .filter((t) => t.reviewStatus !== "reviewed")
    .sort(
      (a, b) =>
        (priorityOrder[a.reviewStatus] ?? 5) -
        (priorityOrder[b.reviewStatus] ?? 5)
    )
    .map((company) => {
      const issues: string[] = [];
      if (!company.estimatedRevenue && !company.aum)
        issues.push("Missing revenue and AUM data");
      if (!company.employeeCount) issues.push("Missing employee count");
      if (company.confidenceScore < 60) issues.push("Very low confidence data");
      if (company.reviewStatus === "flagged")
        issues.push("Flagged for regulatory or data issue");
      if (company.reviewStatus === "low_confidence")
        issues.push("Limited public data available");
      if (company.reviewStatus === "needs_validation")
        issues.push("Key fields require cross-validation");
      if (company.reviewStatus === "incomplete")
        issues.push("Missing mandatory fields");

      const priority: "high" | "medium" | "low" =
        company.reviewStatus === "flagged" || company.reviewStatus === "incomplete"
          ? "high"
          : company.reviewStatus === "needs_validation"
            ? "medium"
            : "low";

      return { company, issues, priority };
    });
}
